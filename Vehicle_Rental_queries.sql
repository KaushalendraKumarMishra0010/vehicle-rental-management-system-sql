#Q11.Find the total rental revenue generated by the company.

SELECT SUM(Bill_Amount) AS Total_Revenue
FROM booking;
    
#Q12.Find the average booking bill.

SELECT AVG(Bill_Amount) AS Average_Bill
FROM booking;

#Q13.Find the highest booking bill.

SELECT MAX(Bill_Amount) AS Highest_Bill
FROM booking;

#Q14.Find the total number of bookings.

SELECT COUNT(BID) AS Total_Bookings
FROM booking;

#Q15.Find the total revenue generated from Cars and Bikes separately.

SELECT v.Vehicle_Type,SUM(b.Bill_Amount) AS Total_Revenue
FROM booking b
JOIN vehicle v
    ON b.VID = v.VID
GROUP BY v.Vehicle_Type;

-------------------------------------------------------------------------
                       #Section D — GROUP BY / HAVING
-------------------------------------------------------------------------
   
/* Q16.Find the number of bookings made by each customer.
       Display:
       Customer_Name
	   Number_of_Bookings */

SELECT c.Customer_Name,COUNT(b.BID) AS Number_of_Bookings
FROM customer c
LEFT JOIN booking b
    ON c.CID = b.CID
GROUP BY c.CID, c.Customer_Name;   

/* Q17.Find the total amount spent by each customer.
       Display customers in descending order of total spending. */

SELECT c.Customer_Name,SUM(b.Bill_Amount) AS Total_Spending
FROM customer c
JOIN booking b
    ON c.CID = b.CID
GROUP BY c.CID, c.Customer_Name
ORDER BY Total_Spending DESC;

/* Q18.Find the number of bookings for each vehicle.
       Display:
       Vehicle_Name
	   Number_of_Bookings */
       
SELECT v.Vehicle_Name,COUNT(b.BID) AS Number_of_Bookings
FROM vehicle v
LEFT JOIN booking b
    ON v.VID = b.VID
GROUP BY v.VID,v.Vehicle_Name;

#Q19.Find vehicle types having more than 3 bookings.

SELECT v.Vehicle_Type,COUNT(b.BID) AS Number_of_Bookings
FROM vehicle v
JOIN booking b
    ON v.VID = b.VID
GROUP BY v.Vehicle_Type
HAVING COUNT(b.BID) > 3;

/* Q20. Find the top 3 customers who have generated the highest rental revenue.
        Display:
	    Customer_Name
        Number_of_Bookings
        Total_Spending */

SELECT Customer_Name,Number_of_Bookings,Total_Spending
FROM
    (SELECT c.Customer_Name,COUNT(b.BID) AS Number_of_Bookings,
           SUM(b.Bill_Amount) AS Total_Spending,
           DENSE_RANK() OVER (ORDER BY SUM(b.Bill_Amount) DESC
           ) AS Revenue_Rank
      FROM customer c
      JOIN booking b
          ON c.CID = b.CID
      GROUP BY c.CID, c.Customer_Name
) T
WHERE Revenue_Rank <= 3;



