#Q6.Display the customer name, vehicle name, start date and end date for every booking.

SELECT c.Customer_Name,v.Vehicle_Name,b.Start_Date,b.End_Date
FROM customer c
JOIN booking b
    ON c.CID = b.CID
JOIN vehicle v
    ON b.VID = v.VID;

#Q7.Display customer name, phone number, vehicle name and bill amount for all bookings.

SELECT c.Customer_Name,c.Phone,v.Vehicle_Name,b.Bill_Amount
FROM customer c
JOIN booking b
	ON c.CID=b.CID
JOIN vehicle v
ON b.VID=v.VID;

#Q8.Display all bookings for Cars along with customer details.

SELECT b.*,c.Customer_Name,c.Phone,
	   c.Age,c.Licence_Number,c.Address
FROM customer c
JOIN booking b
    ON c.CID=b.CID
JOIN vehicle v
    ON b.VID=v.VID
WHERE v.Vehicle_Type='Car';

#Q9.Display all customers who have made at least one booking.

SELECT DISTINCT c.*
FROM customer c
JOIN booking b
    ON c.CID = b.CID;
    
#Q10.Display all vehicles that have been booked at least once.
    
SELECT DISTINCT v.*
FROM vehicle v
JOIN booking b
    ON v.VID = b.VID;
    
